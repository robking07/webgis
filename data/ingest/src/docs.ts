// docs/data-sources.md, generated from the registry plus row counts in the database.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { loadRegistry } from "@webgis/registry/load";
import type { DatasetEntry } from "@webgis/registry";
import { describeMethod as method } from "@webgis/registry/describe";
import { db, log, ROOT } from "./util.ts";

export async function writeDataSourcesDoc() {
  const entries = loadRegistry();
  const pool = db();
  const { rows } = await pool.query<{ dataset_id: string; level: string; n: string; nv: string }>(
    "select dataset_id, level, count(*) n, count(value) nv from public.dataset_values group by 1, 2");
  await pool.end();
  const counts = new Map(rows.map((r) => [`${r.dataset_id}/${r.level}`, `${(+r.nv).toLocaleString()} of ${(+r.n).toLocaleString()}`]));
  const bySource = new Map<string, DatasetEntry[]>();
  for (const e of entries) (bySource.get(e.source.name) ?? bySource.set(e.source.name, []).get(e.source.name)!).push(e);

  const md = `# Data sources

> Generated by \`npm run ingest -- docs\` from \`data/registry/datasets/*.yaml\` and the database. Don't edit by hand.

${entries.length} datasets from ${bySource.size} sources, all free and federal (SPEC Phase 1), all public domain. Boundaries: U.S. Census Bureau 2024 cartographic boundary files (500k), Gazetteer 2024 for land area and internal points.

**Adding a dataset** = one YAML file in \`data/registry/datasets/\` (validated by \`data/registry/schema.ts\`), plus an ingest script only if it's a new kind of source. See the \`add-dataset\` project skill.

${[...bySource].map(([src, es]) => `## ${src}

- Source: ${es[0].source.url}
- License: ${es[0].license}
- Update cadence: ${es[0].updateCadence}
${es[0].coverageNote ? `- Coverage: ${es[0].coverageNote}\n` : ""}
| Dataset | Levels (non-null / rows) | Unit | Vintage | Method |
|---|---|---|---|---|
${es.map((e) => `| **${e.title}** (\`${e.id}\`) | ${e.measure.kind === "features" ? "road segments (feature layer)" : ""}${e.geographyLevels.map((l) => `${l}: ${counts.get(`${e.id}/${l}`) ?? "not loaded"}`).join("<br>")} | ${e.unit} | ${e.vintage} | ${method(e)}${e.modelInputs.length ? ` Modeled using: ${e.modelInputs.join(", ")} (insight pairs with those are flagged).` : ""} |`).join("\n")}
`).join("\n")}
## Known gaps and caveats

- **LODES:** Alaska has no WAC file since 2016 (shown as no data); Michigan's latest is 2021; Puerto Rico isn't covered (D-14).
- **PLACES:** model-based small-area estimates (BRFSS + multilevel regression and poststratification), not direct counts. County poverty is a model input, so PLACES × poverty/income correlations are partly by construction (D-17).
- **nClimDiv:** Connecticut uses pre-2022 county codes and Hawaii has no county series, so both show no data for climate.
- **ACS:** 5-year estimates describe 2020–2024 as a period, not a single year. Small tracts carry large margins of error, which the detail panel shows.
`;
  writeFileSync(join(ROOT, "docs/data-sources.md"), md);
  log("docs", `data-sources.md: ${entries.length} datasets`);
}
