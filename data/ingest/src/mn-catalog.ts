// Minnesota Geospatial Commons catalog (D-16): lists every feature service with its
// publisher and license text, classifies the license, and writes a review list to
// docs/mn-commons-catalog.md + data/registry/mn-commons-catalog.json. Ingests nothing:
// SPEC §10 requires a license decision per source before republishing.
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { log, ROOT } from "./util.ts";

const API = "https://gis.data.mn.gov/api/search/v1/collections/all/items";

type LicenseClass = "public-domain" | "license-agreement" | "custom-terms" | "none-stated";
interface Item { id: string; title: string; publisher: string; url: string; license: LicenseClass; licenseText: string; tags: string[]; parcels: boolean }

function classify(text: string): LicenseClass {
  const t = text.toLowerCase();
  if (!t.trim() || t.includes("not provided a use license")) return "none-stated";
  if (t.includes("public domain")) return "public-domain";
  if (t.includes("license agreement")) return "license-agreement";
  return "custom-terms";
}
const strip = (h: string) => h.replace(/<[^>]+>/g, " ").replace(/&nbsp;/g, " ").replace(/&amp;/g, "&").replace(/\s+/g, " ").trim();

export async function mnCatalog() {
  const items: Item[] = [];
  for (let start = 1; ; start += 100) {
    const res = await fetch(`${API}?limit=100&startindex=${start}&type=Feature%20Service`);
    if (!res.ok) throw new Error(`MN Commons catalog → ${res.status}`);
    const page = (await res.json()) as { features: Array<{ properties: Record<string, unknown> }> };
    for (const f of page.features) {
      const p = f.properties as Record<string, string & string[]>;
      const licenseText = strip(String(p.licenseInfo ?? ""));
      items.push({
        id: String(p.id), title: String(p.title), publisher: String(p.source ?? p.owner ?? "?"), url: String(p.url ?? ""),
        license: classify(licenseText), licenseText: licenseText.slice(0, 400), tags: (p.tags as string[]) ?? [],
        parcels: /parcel/i.test(String(p.title)),
      });
    }
    if (page.features.length < 100) break;
  }
  mkdirSync(join(ROOT, "data/registry"), { recursive: true });
  writeFileSync(join(ROOT, "data/registry/mn-commons-catalog.json"), JSON.stringify(items, null, 1));

  const byPub = new Map<string, Item[]>();
  for (const i of items) (byPub.get(i.publisher) ?? byPub.set(i.publisher, []).get(i.publisher)!).push(i);
  const count = (c: LicenseClass) => items.filter((i) => i.license === c).length;
  const pubs = [...byPub].sort((a, b) => b[1].length - a[1].length);
  const md = `# Minnesota Geospatial Commons: catalog for review

> Generated by \`npm run ingest -- mn-catalog\` on ${new Date().toISOString().slice(0, 10)}. Full list with license text: \`data/registry/mn-commons-catalog.json\`.

**Nothing here is ingested yet.** Robbie asked to include all of it (D-16). Publicly published Met Council open data is allowed. What's left before ingest:

1. **License per publisher** (SPEC §10). Classes below come from each item's license field; "custom terms" and "license agreement" need a human read before republishing.
2. **A feature-layer registry kind.** Most of these are points, lines or non-Census polygons, which need a new \`measure.kind\` and a non-choropleth renderer (D-16).
3. **Parcels** (${items.filter((i) => i.parcels).length} services) stay out until we decide on size and privacy (owner names).

| License class | Services |
|---|---|
| Public domain | ${count("public-domain")} |
| License agreement (e.g. DNR GIS Data License Agreement) | ${count("license-agreement")} |
| Custom terms | ${count("custom-terms")} |
| None stated | ${count("none-stated")} |
| **Total** | **${items.length}** |

Proposed first batch (default if Robbie doesn't say otherwise): **public-domain, non-parcel** services, which can go in once the feature-layer kind exists (${items.filter((i) => i.license === "public-domain" && !i.parcels).length} services).

## By publisher

| Publisher | Services | Public domain | Agreement | Custom | None |
|---|---|---|---|---|---|
${pubs.map(([p, is]) => `| ${p} | ${is.length} | ${is.filter((i) => i.license === "public-domain").length} | ${is.filter((i) => i.license === "license-agreement").length} | ${is.filter((i) => i.license === "custom-terms").length} | ${is.filter((i) => i.license === "none-stated").length} |`).join("\n")}

## Representative license texts (one per publisher, first item)

${pubs.slice(0, 15).map(([p, is]) => `- **${p}** (${is[0].license}): ${is[0].licenseText ? `“${is[0].licenseText.slice(0, 220)}${is[0].licenseText.length > 220 ? "…" : ""}”` : "(empty)"}`).join("\n")}
`;
  writeFileSync(join(ROOT, "docs/mn-commons-catalog.md"), md);
  log("mn-catalog", `${items.length} services, ${byPub.size} publishers → docs/mn-commons-catalog.md`);
}
