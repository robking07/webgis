// U.S. label mask: the polygon the basemap uses to tell U.S. place labels from foreign ones
// (OpenMapTiles city/state points carry no country code). Written to
// packages/design/src/us-label-mask.ts and used with MapLibre's `within` filter.
//
// Shape: the Census nation outline buffered 0.3° out to sea, minus Canada, Mexico and the
// nearby islands (Natural Earth, public domain). The land borders stay exact; coasts are
// loose so shoreline cities, keys and islands stay inside. Checked against border pairs
// (Windsor/Detroit, Tijuana/San Diego, Juárez/El Paso, Sault Ste. Marie ON/MI, Point Roberts…).
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { spawnSync } from "node:child_process";
import { cached, CACHE, log, ROOT } from "./util.ts";

const NATION = "https://www2.census.gov/geo/tiger/GENZ2024/shp/cb_2024_us_nation_5m.zip";
const NE = "https://naciscdn.org/naturalearth/10m/cultural/ne_10m_admin_0_countries.zip";
const NEIGHBORS = ["CAN", "MEX", "CUB", "BHS", "RUS", "GTM", "BLZ"];

function ogr(args: string[]) {
  const r = spawnSync("ogr2ogr", args, { encoding: "utf8" });
  if (r.status !== 0) throw new Error(`ogr2ogr failed: ${r.stderr}`);
}

export async function buildLabelMask() {
  const nation = await cached(NATION);
  const ne = await cached(NE);
  const dir = join(CACHE, "label-mask");
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  const db = join(dir, "work.sqlite"), out = join(dir, "mask.json");
  ogr(["-f", "SQLite", "-dsco", "SPATIALITE=YES", db, `/vsizip/${nation}`, "-nln", "us", "-nlt", "MULTIPOLYGON"]);
  ogr(["-append", "-f", "SQLite", db, `/vsizip/${ne}`, "-nln", "ne", "-nlt", "MULTIPOLYGON",
    "-where", `ADM0_A3 IN (${NEIGHBORS.map((c) => `'${c}'`).join(",")})`]);
  ogr(["-f", "GeoJSON", "-lco", "COORDINATE_PRECISION=3", out, db, "-dialect", "SQLite", "-sql",
    "SELECT ST_Simplify(ST_Difference(ST_Buffer(ST_Simplify(u.GEOMETRY, 0.02), 0.3), (SELECT ST_Union(ST_MakeValid(GEOMETRY)) FROM ne)), 0.01) AS geom FROM us u"]);
  const geometry = JSON.parse(readFileSync(out, "utf8")).features[0].geometry;
  const target = join(ROOT, "packages/design/src/us-label-mask.ts");
  writeFileSync(target,
    "// Generated by `npm run ingest -- label-mask` (data/ingest/src/label-mask.ts). Do not edit.\n" +
    "// U.S. land (coasts buffered out to sea) for telling U.S. place labels from foreign ones.\n" +
    `export const US_LABEL_MASK = ${JSON.stringify({ type: geometry.type, coordinates: geometry.coordinates })} as const;\n`);
  log("label-mask", `${geometry.coordinates.length} polygons → ${target}`);
}
