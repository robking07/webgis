#!/usr/bin/env node
// Session brief (issue #131): a short "where things stand" built fresh
// from the sources of truth, so a new Claude session (or a person) can pick up work fast.
// The SessionStart hook in .claude/settings.json runs it; its output becomes session context.
//
//   node scripts/brief.mjs        # the brief
//   node scripts/brief.mjs 127    # the brief's task view for one issue: body, comments, PRs
//
// Nothing here is hand-kept, so nothing goes stale. It also flags label drift and memory
// files past their `stale_after:` date. GitHub sections are skipped (with a note)
// when `gh` is missing, offline or not signed in. Keep the output under ~3k tokens.
import { execFile } from "node:child_process";
import { readFileSync, readdirSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { promisify } from "node:util";

const run = promisify(execFile);
const sh = async (cmd, args) => {
  try {
    const { stdout } = await run(cmd, args, { timeout: 15000, maxBuffer: 8 << 20 });
    return stdout;
  } catch {
    return null;
  }
};
const ghJson = async (args) => {
  const out = await sh("gh", args);
  return out ? JSON.parse(out) : null;
};
const read = (p) => {
  try {
    return readFileSync(p, "utf8");
  } catch {
    return "";
  }
};
const clip = (s, n) => (s.length > n ? s.slice(0, n - 1) + "…" : s);

const issueArg = process.argv[2]?.replace(/^#/, "");
if (issueArg) {
  await task(issueArg);
} else {
  await brief();
}

async function brief() {
  const [head, wt, churn, issues, prs, gitCommon] = await Promise.all([
    sh("git", ["log", "-1", "--format=%h %cs %s"]),
    sh("git", ["worktree", "list", "--porcelain"]),
    sh("git", ["log", "--since=21.days", "--name-only", "--format="]),
    ghJson(["issue", "list", "--state", "open", "--limit", "100", "--json", "number,title,labels"]),
    ghJson(["pr", "list", "--state", "open", "--json", "number,title,isDraft,headRefName,statusCheckRollup,mergeStateStatus,body"]),
    sh("git", ["rev-parse", "--path-format=absolute", "--git-common-dir"]),
  ]);

  const out = [];
  out.push(`# Session brief (generated by scripts/brief.mjs, ${new Date().toISOString().slice(0, 10)})`);
  out.push(`main checkout HEAD: ${head?.trim() ?? "?"}. Deeper: docs/architecture.md (code map), docs/roadmap.md, docs/progress.md. Task view: \`node scripts/brief.mjs <issue>\`.`);

  // 1. The hand-written handoff: progress log "Now".
  const now = read("docs/progress.md").match(/## Now\n([\s\S]*?)\n## /)?.[1].trim();
  if (now) out.push("", "## Now (docs/progress.md)", now);

  // 2. GitHub: issues by label, open PRs.
  out.push("", "## GitHub");
  if (!issues) {
    out.push("(skipped: `gh` unavailable or not signed in)");
  } else {
    const byLabel = (l) => issues.filter((i) => i.labels.some((x) => x.name === l));
    const line = (i) => `#${i.number} ${clip(i.title, 80)}`;
    for (const [label, name] of [
      ["needs-robbie", "Waiting on Robbie"],
      ["building", "Building"],
      ["queued", "Queued"],
      ["approved", "Approved"],
    ]) {
      const list = byLabel(label);
      if (list.length) out.push(`- **${name}:** ${list.map(line).join("; ")}`);
    }
    const shown = new Set(["needs-robbie", "building", "queued", "approved"]);
    const rest = issues.filter((i) => !i.labels.some((x) => shown.has(x.name)));
    if (rest.length) out.push(`- **Other open (${rest.length}):** ${rest.map((i) => `#${i.number}`).join(" ")}`);

    // Label drift: each open, unparked issue has exactly one state label (.claude/agents/lead.md).
    const STATES = ["idea", "needs-robbie", "queued", "approved", "building"];
    const drift = [];
    for (const i of issues) {
      const names = i.labels.map((x) => x.name);
      if (names.includes("parked")) continue;
      const states = names.filter((n) => STATES.includes(n));
      if (states.length !== 1) drift.push(`#${i.number} has ${states.length ? states.join(" + ") : "no state label"}`);
      else if (states[0] === "building" && prs && !prs.some((p) => new RegExp(`#${i.number}\\b`).test(p.body ?? "")))
        drift.push(`#${i.number} is building with no open PR`);
    }
    if (drift.length) out.push(`- **Fix labels:** ${drift.join("; ")}`);
  }
  if (prs) {
    const checks = (p) => {
      const r = p.statusCheckRollup ?? [];
      const bad = r.filter((c) => ["FAILURE", "ERROR", "TIMED_OUT", "CANCELLED"].includes(c.conclusion ?? c.state));
      const pending = r.filter((c) => c.status && c.status !== "COMPLETED");
      return bad.length ? `failing: ${bad.map((c) => c.name ?? c.context).join(", ")}` : pending.length ? "checks running" : r.length ? "green" : "no checks";
    };
    out.push(`- **Open PRs:** ${prs.length ? "" : "none"}`);
    for (const p of prs)
      out.push(`  - #${p.number} ${clip(p.title, 70)} [${p.headRefName}] ${p.isDraft ? "draft" : "ready"}, ${checks(p)}${p.mergeStateStatus === "BEHIND" ? ", behind main" : ""}`);
  }

  // Memory facts past their `stale_after: YYYY-MM-DD` (frontmatter); re-check or update them.
  const root = gitCommon ? dirname(gitCommon.trim()) : process.cwd();
  const memDir = join(homedir(), ".claude", "projects", root.replace(/[^A-Za-z0-9]/g, "-"), "memory");
  const today = new Date().toISOString().slice(0, 10);
  let memFiles = [];
  try {
    memFiles = readdirSync(memDir).filter((f) => f.endsWith(".md"));
  } catch {}
  const stale = memFiles
    .map((f) => [f, read(join(memDir, f)).match(/^\s*stale_after:\s*["']?(\d{4}-\d{2}-\d{2})/m)?.[1]])
    .filter(([, d]) => d && d < today);
  if (stale.length) out.push("", "## Stale memory (past stale_after; verify, then update the fact and date)", stale.map(([f, d]) => `- ${f} (stale since ${d})`).join("\n"));

  // 3. Worktrees (each task has one; stale ones need Robbie's OK to delete).
  const trees = (wt ?? "").split("\n\n").map((b) => ({
    path: b.match(/^worktree (.*)$/m)?.[1],
    branch: b.match(/^branch refs\/heads\/(.*)$/m)?.[1] ?? "(detached)",
  })).filter((t) => t.path?.includes(".claude/worktrees/"));
  if (trees.length) {
    const prBranch = new Map((prs ?? []).map((p) => [p.headRefName, p.number]));
    out.push("", "## Worktrees");
    for (const t of trees)
      out.push(`- ${t.path.split(".claude/worktrees/")[1]} → ${t.branch}${prBranch.has(t.branch) ? ` (PR #${prBranch.get(t.branch)})` : prs ? " (no open PR)" : ""}`);
  }

  // 4. Datasets, from the registry (the single source of truth).
  const dir = "data/registry/datasets";
  const cats = new Map();
  let n = 0;
  for (const f of readdirSync(dir).filter((f) => f.endsWith(".yaml")).sort()) {
    const y = read(`${dir}/${f}`);
    const field = (k) => y.match(new RegExp(`^${k}:\\s*(.*)$`, "m"))?.[1]?.replace(/^["']|["']$/g, "") ?? "";
    const kind = y.match(/^measure:.*?kind:\s*(\w+)/ms)?.[1] ?? "?";
    const levels = field("geographyLevels").replace(/[[\]\s]/g, "").split(",").map((l) => ({ state: "S", county: "C", tract: "T", block_group: "BG" })[l] ?? l).join("");
    const cat = field("category") || "Other";
    if (!cats.has(cat)) cats.set(cat, []);
    cats.get(cat).push(`${field("id") || f.replace(".yaml", "")} (${kind}${levels ? " " + levels : ""})`);
    n++;
  }
  out.push("", `## Datasets (${n}; kind + levels S/C/T/BG; data/registry/datasets)`);
  for (const [cat, list] of cats) out.push(`- **${cat}:** ${list.join(", ")}`);

  // 5. Decisions D-100+, with the code that cites them.
  const ddir = "docs/decisions";
  const cites = await sh("git", ["grep", "-n", "-o", "-E", "D-[0-9]{3}", "--", "apps", "packages", "data", "scripts", ".claude", ":!*/generated/*", ":!*.json"]);
  const citedBy = new Map();
  for (const l of (cites ?? "").split("\n")) {
    const m = l.match(/^([^:]+):\d+:(D-\d{3})$/);
    if (!m) continue;
    if (!citedBy.has(m[2])) citedBy.set(m[2], new Set());
    citedBy.get(m[2]).add(m[1].replace(/^apps\/web\/src\//, "web/"));
  }
  out.push("", "## Decisions (docs/decisions; D-01–D-99 frozen in docs/DECISIONS.md)");
  for (const f of readdirSync(ddir).filter((f) => /^D-\d+/.test(f)).sort()) {
    const d = read(`${ddir}/${f}`);
    const id = f.match(/^D-\d+/)[0];
    const title = d.match(/^# D-\d+ [·-] (.*)$/m)?.[1] ?? f;
    const status = d.match(/\*\*Status:\*\*\s*(\w+)/)?.[1] ?? (/Decided by/i.test(d) ? "DECIDED" : "");
    const files = [...(citedBy.get(id) ?? [])];
    out.push(`- ${id} ${title}${status ? ` [${status}]` : ""}${files.length ? ` — cited in ${files.slice(0, 3).join(", ")}${files.length > 3 ? ` +${files.length - 3}` : ""}` : ""}`);
  }

  // 6. Hot spots: most-changed code in the last 3 weeks (collision risk for parallel workers).
  const skip = /(^docs\/|generated\/|package-lock|CHANGELOG|\.md$|\.json$)/;
  const counts = new Map();
  for (const f of (churn ?? "").split("\n").filter((f) => f && !skip.test(f))) counts.set(f, (counts.get(f) ?? 0) + 1);
  const hot = [...counts].sort((a, b) => b[1] - a[1]).slice(0, 10);
  if (hot.length) out.push("", "## Hot spots (commits touching each, last 21 days; two workers here collide)", hot.map(([f, c]) => `${f} ${c}`).join(" · "));

  console.log(out.join("\n"));
}

async function task(n) {
  const issue = await ghJson(["issue", "view", n, "--json", "number,title,state,labels,body,comments,url"]);
  if (!issue) {
    console.log(`Couldn't read issue #${n} (is \`gh\` signed in?).`);
    return;
  }
  const out = [`# #${issue.number} ${issue.title} [${issue.state}; ${issue.labels.map((l) => l.name).join(", ")}]`, issue.url, "", issue.body.trim()];
  const recent = issue.comments.slice(-5);
  if (recent.length) {
    out.push("", `## Latest comments (${recent.length} of ${issue.comments.length})`);
    for (const c of recent) out.push(`- **${c.author.login}, ${c.createdAt.slice(0, 10)}:** ${clip(c.body.trim().replace(/\n+/g, " "), 600)}`);
  }
  const prs = await ghJson(["pr", "list", "--state", "all", "--search", `${n} in:body`, "--json", "number,title,state,isDraft,headRefName,url"]);
  const linked = prs ?? [];
  if (linked.length) {
    out.push("", "## PRs mentioning it");
    for (const p of linked) out.push(`- #${p.number} ${p.title} [${p.state}${p.isDraft ? ", draft" : ""}] ${p.headRefName}`);
  }
  console.log(out.join("\n"));
}
